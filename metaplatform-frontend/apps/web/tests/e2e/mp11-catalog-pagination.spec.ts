import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { test, expect } from '@playwright/test';
import { injectAuthIntoPage } from './helpers/auth';
test.use({ trace: 'off', video: 'off', screenshot: 'off' });
const session = () => JSON.parse(readFileSync(process.env.MP11_SESSION_FILE!, 'utf8')).catalog;
const headers = () => ({ Authorization: 'Bearer ' + session().token });
const api = () => process.env.MP11_API_URL!;
function receipt(name: string, details: object) {
  const s = session();
  const root = path.resolve(path.dirname(process.env.MP11_API_EVIDENCE!), '../mp11-final-fix');
  writeFileSync(path.join(root, name + '-' + s.run_id + '.json'), JSON.stringify({ run_id: s.run_id, tenant: s.tenant, ...details }, null, 2));
}
test('late-page Order and Customer can be mapped to actual PG columns and synced', async ({ page, request }) => {
  const s = session();
  const first = await request.get(api() + '/ont/v2/object-types', { headers: headers(), params: { limit: 100, offset: 0 } });
  const later = await request.get(api() + '/ont/v2/object-types', { headers: headers(), params: { limit: 100, offset: 100 } });
  expect(first.ok() && later.ok()).toBeTruthy();
  const firstRows = await first.json(), laterRows = await later.json();
  expect(firstRows).toHaveLength(100);
  expect(laterRows.map((x: { rid: string }) => x.rid)).toEqual(expect.arrayContaining([s.order, s.customer]));
  expect(firstRows.some((x: { rid: string }) => x.rid === s.order || x.rid === s.customer)).toBe(false);
  expect([...firstRows, ...laterRows].every(x => x.rid.startsWith('ont.' + s.tenant + '.'))).toBe(true);
  await injectAuthIntoPage(page, s.token, { tenantId: s.tenant });
  await page.goto('/ontology/data/mappings?source=' + s.source_id);
  await page.getByLabel('对象类型', { exact: true }).selectOption(s.order);
  await expect(page.getByLabel('对象类型', { exact: true }).getByRole('option', { name: 'Late Customer', exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: '验证连接并发现字段', exact: true }).click();
  await page.getByLabel('源表', { exact: true }).selectOption('mp11_ui_source.orders');
  await page.getByLabel('时间列', { exact: true }).selectOption('modified_at');
  await page.getByLabel('确认字段映射', { exact: true }).check();
  const saved = page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes('/datasources') && !r.url().includes('/sync'));
  await page.getByRole('button', { name: '预检并保存映射', exact: true }).click();
  const response = await saved; expect(response.ok()).toBeTruthy();
  const mapping = await response.json();
  await page.getByRole('button', { name: '全量同步 / CSV批量导入', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: /写入 2/ })).toBeVisible();
  const stored = await request.get(api() + '/ont/v2/object-types/' + s.order + '/datasources', { headers: headers() });
  expect(stored.ok()).toBeTruthy();
  const persisted = (await stored.json()).find((x: { rid: string }) => x.rid === mapping.rid);
  expect(persisted.source_id).toBe(s.source_id);
  expect(persisted.field_mapping['ont.' + s.tenant + '.prop.total']).toBe('total');
  receipt('catalog-mapping', { order: s.order, customer: s.customer, mapping_id: mapping.rid, persisted: true, actual_pg_rows: 2 });
});
test('late-page Order and Customer bind actual app fields and survive saved page reopening', async ({ page, request }) => {
  const s = session();
  await injectAuthIntoPage(page, s.token, { tenantId: s.tenant });
  await page.goto('/apps/mine');
  await page.getByLabel('订单应用名称', { exact: true }).fill('Late catalog app ' + s.run_id);
  await page.getByRole('button', { name: '创建订单审核应用', exact: true }).click();
  await expect(page.getByRole('heading', { name: /页面设计器/ })).toBeVisible();
  const designer = page.url(), pageId = new URL(designer).searchParams.get('page')!;
  await page.getByLabel('订单对象', { exact: true }).selectOption(s.order);
  await page.getByLabel('客户对象', { exact: true }).selectOption(s.customer);
  await page.getByLabel('客户关系', { exact: true }).selectOption(s.link);
  await page.getByLabel('审核动作', { exact: true }).selectOption(s.action);
  await expect(page.getByText('total（integer）', { exact: true })).toBeVisible();
  const saved = page.waitForResponse(r => r.url().endsWith('/pages/' + pageId) && r.request().method() === 'PUT');
  await page.getByRole('button', { name: /保存$/ }).click();
  expect((await saved).ok()).toBeTruthy();
  await page.goto(designer);
  await expect(page.getByLabel('订单对象', { exact: true })).toHaveValue(s.order);
  await expect(page.getByLabel('客户对象', { exact: true })).toHaveValue(s.customer);
  const stored = await request.get(api() + '/apphub/pages/' + pageId, { headers: headers() });
  expect(stored.ok()).toBeTruthy();
  receipt('catalog-binding', { page_id: pageId, order: s.order, customer: s.customer, actual_fields_visible: true, saved_reopened: true });
});
test('late-page onboarding model is retained across reload and revalidation for the signed tenant', async ({ page }) => {
  const s = session();
  await injectAuthIntoPage(page, s.token, { tenantId: s.tenant });
  await page.goto('/home');
  const guide = page.getByRole('region', { name: '开始使用平台' });
  await guide.getByRole('button', { name: '接入真实数据', exact: true }).click();
  await guide.getByLabel('本次数据源', { exact: true }).selectOption(s.source_id);
  await guide.getByLabel('本次对象模型', { exact: true }).selectOption(s.order);
  await expect(guide.getByLabel('本次对象模型', { exact: true }).getByRole('option', { name: 'Late Customer', exact: true })).toHaveCount(1);
  await page.reload();
  await expect(guide.getByLabel('本次对象模型', { exact: true })).toHaveValue(s.order);
  await guide.getByRole('button', { name: '重新核验产物', exact: true }).click();
  await expect(guide.getByLabel('本次对象模型', { exact: true })).toHaveValue(s.order);
  await expect(guide.getByRole('alert')).toHaveCount(0);
  receipt('catalog-onboarding', { order: s.order, customer: s.customer, signed_subject: s.subject, retained_after_reload: true, retained_after_revalidation: true });
});
