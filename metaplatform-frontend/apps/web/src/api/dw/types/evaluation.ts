/** Evaluation automation domain types shared by DW APIs and agent UI. */
export type EvaluationDimension =
  | 'accuracy'
  | 'relevance'
  | 'completeness'
  | 'clarity'
  | 'safety'
  | 'efficiency';

export interface DimensionScore {
  dimension: EvaluationDimension;
  score: number;
  weight?: number;
  reasoning?: string;
  evidence?: string[];
}

export type EvaluationMode = 'automatic' | 'manual' | 'hybrid';

export interface AutoScoreResult {
  conversationId: string;
  overallScore: number;
  dimensions: DimensionScore[];
  summary: string;
  evaluatorModel: string;
  evaluatedAt: string;
  mode: EvaluationMode;
}

export type SuggestionCategory =
  | 'prompt'
  | 'knowledge'
  | 'tool'
  | 'workflow'
  | 'model'
  | 'quality';
export type SuggestionPriority = 'high' | 'medium' | 'low';

export interface OptimizationSuggestion {
  id: string;
  employeeId: string;
  category: SuggestionCategory;
  priority: SuggestionPriority;
  title: string;
  description: string;
  action: string;
  expectedImpact: string;
  relatedEvidence?: string[];
  createdAt?: string;
}

export interface GenerateSuggestionsRequest {
  employeeId: string;
  period?: string;
  reportId?: string;
}

export interface GenerateSuggestionsResponse {
  suggestions: OptimizationSuggestion[];
  generatedAt: string;
}

export interface EvaluationReportDetail {
  reportId: string;
  employeeId: string;
  period: string;
  totalTasks: number;
  avgQualityScore: number;
  successRate: number;
  avgDuration: number;
  highlights: string[];
  issues: string[];
  createdAt: string;
  autoGenerated?: boolean;
  dimensions?: DimensionScore[];
  suggestions?: OptimizationSuggestion[];
  scoreBreakdown?: Record<string, number>;
  comparisonBaseline?: {
    previousScore: number;
    delta: number;
  };
}

export interface ScoringRubric {
  id: string;
  name: string;
  description?: string;
  dimensions: Array<{
    dimension: EvaluationDimension;
    weight: number;
    criteria: string;
  }>;
  enabled?: boolean;
  createdAt?: string;
  updatedAt?: string;
}

