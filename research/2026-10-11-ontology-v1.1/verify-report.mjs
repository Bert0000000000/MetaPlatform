import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
const root=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(root,'../..');
const require=createRequire(import.meta.url);
const {chromium}=require(path.join(repo,'metaplatform-frontend/node_modules/playwright'));
const artifacts=path.join(root,'artifacts');await fs.mkdir(artifacts,{recursive:true});
const errors=[];const results=[];
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(root,'metaplatform-v1.1-research.html')).href,{waitUntil:'load'});
 await page.screenshot({path:path.join(artifacts,'report-desktop.png')});
 const repositoryRows=await page.locator('.repositorywrap tbody tr').count();
 if(repositoryRows!==20)throw Error('Expected 20 repositories; got '+repositoryRows);
 const header=await page.locator('.repositorywrap thead').innerText();
 if(!header.includes('License'))throw Error('License column missing');
 await page.locator('#repository-filter').fill('open-metadata/OpenMetadata');
 if(await page.locator('.repositorywrap tbody tr:visible').count()!==1)throw Error('Project filter failed');
 await page.locator('#repository-filter').fill('zzzz-not-a-repo');
 if(await page.locator('.repositorywrap tbody tr:visible').count()!==0)throw Error('Empty filter failed');
 await page.locator('#repository-filter').fill('');
 await page.locator('.repositorywrap').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(artifacts,'report-table.png')});
 await page.locator('#tab-spec').click();
 if(!await page.locator('#spec').isVisible())throw Error('Spec tab failed');
 const requirementIds=await page.locator('#spec').innerText();
 const ids=[...new Set(requirementIds.match(/MP11-[A-Z]+-\d+/g))];
 if(ids.length!==32)throw Error('Expected 32 requirements; got '+ids.length);
 await page.locator('#tab-spec').focus();await page.keyboard.press('ArrowLeft');
 if(!await page.locator('#research').isVisible())throw Error('Keyboard tabs failed');
 await page.locator('button[data-section="官网"]').click();
 if(!await page.locator('#spec').isVisible())throw Error('Flow section navigation failed');
 await page.locator('#tab-research').click();
 await page.locator('.websiteplan').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(artifacts,'report-website-design.png')});
 const internalBroken=await page.locator('a[href^="#"]').evaluateAll(links=>links.filter(a=>a.getAttribute('href')!=='#product-spec'&&!document.getElementById(a.getAttribute('href').slice(1))).map(a=>a.getAttribute('href')));
 if(internalBroken.length)throw Error('Broken anchors: '+internalBroken.join(','));
 const externalBad=await page.locator('a[href^="https://"]').evaluateAll(links=>links.filter(a=>!a.rel.includes('noopener')).map(a=>a.href));
 if(externalBad.length)throw Error('Unsafe external target attributes');
 results.push({viewport:'1440x1000',repositoryRows,requirements:ids.length,filter:'pass',tabs:'pass',keyboard:'pass',anchors:'pass'});
 for(const width of [360,390,768]){
  await page.setViewportSize({width,height:900});await page.evaluate(()=>window.scrollTo(0,0));
  const sizes=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
  if(sizes.document>sizes.viewport+1)throw Error('Horizontal overflow at '+width+': '+JSON.stringify(sizes));
  await page.locator('#tab-spec').click();
  if(!await page.locator('#spec').isVisible())throw Error('Mobile spec tab failed at '+width);
  await page.locator('#tab-research').click();await page.evaluate(()=>window.scrollTo(0,0));
  if(width===390)await page.screenshot({path:path.join(artifacts,'report-mobile.png')});
  results.push({viewport:width+'x900',overflow:'none',tabs:'pass'});
 }
 const noJs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:900}});
 const fallback=await noJs.newPage();await fallback.goto(pathToFileURL(path.join(root,'metaplatform-v1.1-research.html')).href);
 if(!await fallback.locator('#research').isVisible()||!await fallback.locator('#spec').isVisible())throw Error('Offline/no-JS fallback missing');
 await noJs.close();results.push({javascript:'disabled',bothDocuments:'visible'});
 if(errors.length)throw Error('Browser errors: '+errors.join(';'));
 await fs.writeFile(path.join(artifacts,'report-qa.json'),JSON.stringify({status:'passed',results,pageErrors:errors},null,2));
 console.log(JSON.stringify({status:'passed',results,pageErrors:errors,artifacts}));
} finally {await browser.close()}
